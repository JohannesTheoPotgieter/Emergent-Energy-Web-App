export async function seedMockIntakeData() {
  const existing = await db.select({ id: mockSpItems.id }).from(mockSpItems).limit(1);
  if (existing.length > 0) {
    console.log("[Seed] Mock intake items already exist, skipping.");
    return;
  }

  for (const item of MOCK_INTAKE_ITEMS) {
    await db.insert(mockSpItems).values({
      mockItemId: item.mockItemId,
      fields: item.fields,
      etag: `"mock-etag-${item.mockItemId}-v1"`,
      createdDateTime: new Date(Date.now() - Math.random() * 90 * 24 * 60 * 60 * 1000).toISOString(),
      lastModifiedDateTime: new Date().toISOString(),
    });
  }

  console.log(`[Seed] Created ${MOCK_INTAKE_ITEMS.length} mock intake items.`);
}
